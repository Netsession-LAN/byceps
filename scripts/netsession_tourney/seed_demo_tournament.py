from pathlib import Path
import sys

import click

from byceps.services.netsession_tourney.match_generation import (
    generate_stage_matches,
)
from byceps.services.netsession_tourney.models import (
    RegistrationMode,
    StageType,
    TournamentMode,
)
from byceps.services.netsession_tourney.registration_service import (
    register_user,
)
from byceps.services.netsession_tourney.stage_service import create_stage
from byceps.services.netsession_tourney.tournament_service import (
    create_tournament,
)
from byceps.services.user import user_service


sys.path.append(str(Path(__file__).resolve().parents[1]))

from _util import call_with_app_context
from _validators import validate_party, validate_user_screen_name


@click.command()
@click.argument('party', callback=validate_party)
@click.argument('creator', callback=validate_user_screen_name)
@click.option('--slug', default='netsession-demo', show_default=True)
@click.option('--title', default='Netsession Demo Cup', show_default=True)
@click.option('--game', default='Counter-Strike 2', show_default=True)
@click.option('--participants', default=8, type=int, show_default=True)
def execute(party, creator, slug, title, game, participants) -> None:
    click.echo(f'Creating tournament "{title}" ... ', nl=False)
    create_result = create_tournament(
        party.id,
        slug,
        title,
        TournamentMode.duel,
        RegistrationMode.solo,
        creator,
        subtitle='Demo bracket generated by script',
        game=game,
    )
    if create_result.is_err():
        click.secho(f'failed: {create_result.unwrap_err()}', fg='red')
        return

    tournament = create_result.unwrap()
    click.secho('ok', fg='green')

    click.echo('Creating stage ... ', nl=False)
    stage_result = create_stage(
        party.id,
        tournament.id,
        StageType.single_elimination,
        'Main Bracket',
        {},
        creator,
    )
    if stage_result.is_err():
        click.secho(f'failed: {stage_result.unwrap_err()}', fg='red')
        return
    stage = stage_result.unwrap()
    click.secho('ok', fg='green')

    click.echo('Registering demo users ... ', nl=False)
    all_users = sorted(
        user_service.get_all_users(),
        key=lambda user: user.screen_name or '',
    )
    registered_count = 0
    for user in all_users:
        if registered_count >= participants:
            break
        registration_result = register_user(party.id, tournament.id, user)
        if registration_result.is_ok():
            registered_count += 1
    click.secho(f'{registered_count} users', fg='green')

    click.echo('Generating bracket ... ', nl=False)
    generation_result = generate_stage_matches(
        party.id, tournament.id, stage.id, creator
    )
    if generation_result.is_err():
        click.secho(f'failed: {generation_result.unwrap_err()}', fg='red')
        return

    click.secho(
        f'{len(generation_result.unwrap())} matches created.',
        fg='green',
    )
    click.echo(f'Tournament slug: {tournament.slug}')
    click.echo('Open it via: /ns-tourneys/' + tournament.slug)


if __name__ == '__main__':
    call_with_app_context(execute)
